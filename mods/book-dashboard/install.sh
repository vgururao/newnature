#!/bin/zsh
# Vendor the book dashboard into a blygger-studio tree for this node's build.
#   install.sh <studio-tree>
# Use a separate worktree at the version the node runs, never a shared checkout: this edits
# extensions/catalog.ts and extensions.local.json there, and those apply to every node a tree builds.
set -euo pipefail
here=${0:A:h}
tree=${1:?usage: install.sh <studio-tree>}
book=$here/../../book.json
test -f "$tree/extensions/catalog.ts"

mkdir -p "$tree/extensions/book-dashboard"
rm -rf "$tree/extensions/book-dashboard/ui"
cp -R "$here/extension/ui" "$tree/extensions/book-dashboard/ui"
cp "$here/extension/contract.ts" "$here/extension/server.ts" "$here/extension/lookup.ts" "$tree/extensions/book-dashboard/"

/opt/homebrew/bin/python3 - "$book" "$tree" <<'PY'
import json, re, sys
from pathlib import Path
book = json.load(open(sys.argv[1]))
tree = Path(sys.argv[2])
config = {
    "blyg": book["blyg"],
    "notes": book.get("notes", "chapter"),
    "sections": {k: {"role": s["role"], "title": s["title"], **({"id": s["id"]} if s.get("id") else {})} for k, s in book["sections"].items()},
    "references": [r["id"] for r in book.get("references", []) if r.get("id")],
    "indexTerms": book.get("index", {}).get("terms", []),
    **({"menu": book["menu"]} if book.get("menu") else {}),
}
(tree / "extensions/book-dashboard/ui/book.ts").write_text(
    "// Generated by mods/book-dashboard/install.sh from book.json. Do not edit.\n"
    "import type { Book } from './plan.ts';\n"
    f"export const BOOK: Book = {json.dumps(config, ensure_ascii=False, indent=2)};\n", "utf-8")

catalog = tree / "extensions/catalog.ts"
text = catalog.read_text("utf-8")
if '"book-dashboard"' not in text:
    text = re.sub(r"export const EXTENSIONS = \[", 'export const EXTENSIONS = ["book-dashboard", ', text, count=1)
    catalog.write_text(text, "utf-8")

(tree / "extensions.local.json").write_text(json.dumps({"compile": ["word-count", "book-dashboard"]}) + "\n", "utf-8")
PY

echo "book-dashboard vendored into $tree"
